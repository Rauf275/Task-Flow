// ============================================================
// users.js — вспомогательные функции поиска пользователей по id.
// Задачи и участники проектов хранят только userId; отображаемое
// имя всегда получается через эти функции, а не хранится рядом
// с ссылкой (см. требование архитектуры: "не хранить имя
// исполнителя, получать его по assigneeId").
// ============================================================
import { State } from './state.js';

export const Users = {
  get(id) {
    if (!id) return null;
    return State.users.find(u => u.id === id) || null;
  },

  fullName(id) {
    const u = this.get(id);
    return u ? `${u.firstName} ${u.lastName}`.trim() : '';
  },
};
