export function getLang() {
  return State.settings.language === 'en' ? 'en' : 'ru';
}

export function t(key, params) {
  const lang = getLang();
  const entry = (DICT[lang] && DICT[lang][key] !== undefined) ? DICT[lang][key] : DICT.ru[key];
  if (entry === undefined) return key;
  if (typeof entry === 'function') return entry(params || {});
  return entry;
}

// Translates every element in the DOM tagged with data-i18n* attributes.
// - data-i18n="key"              -> element.textContent
// - data-i18n-placeholder="key"  -> element.placeholder
// - data-i18n-title="key"        -> element.title
export function applyStaticTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.documentElement.lang = getLang();
}
